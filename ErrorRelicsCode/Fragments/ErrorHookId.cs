    // H030
    // 来源遗物：Joss Paper
    //
    // 语义：
    // 每累计 Exhaust 自己的 5 张牌时触发一次。
    //
    // 原版：
    // - 非 Ethereal Exhaust 立即累计并检查
    // - Ethereal Exhaust 先暂存在 EtherealCount
    // - 自己一侧回合结束时统一加入 CardsExhausted
    // - CardsExhausted 是 SavedProperty，跨战斗保留
    // =========================================================
