public enum ErrorHookId
{
    // =========================================================
    // H001
    // 来源遗物：Vajra
    //
    // Hook：
    // 进入战斗时
    // =========================================================
    H001_EnterCombat,


    // =========================================================
    // H002
    // 来源遗物：Mercury Hourglass
    //
    // Hook：
    // 自己的回合开始时
    // =========================================================
    H002_PlayerTurnStart,


    // =========================================================
    // H003
    // 来源遗物：Intimidating Helmet
    //
    // Hook：
    // 自己打出一张牌
    // 并且这次打牌使用至少 2 点 Energy
    // =========================================================
    H003_PlayCardEnergy2Plus,


    // =========================================================
    // H004
    // 来源遗物：Old Coin
    //
    // Hook：
    // 获得 / 拾取这件遗物时
    // =========================================================
    H004_AfterObtained,


    // =========================================================
    // H005
    // 来源遗物：Mummified Hand
    //
    // Hook：
    // 战斗中
    // 自己打出一张 Power 牌之后
    // =========================================================
    H005_PowerCardPlayed,


    // =========================================================
    // H006
    // 来源遗物：Distinguished Cape
    //
    // Hook：
    // 获得 / 拾取这件遗物时
    //
    // 和 H004 的 Hook 逻辑完全相同，
    // 但保留独立 Fragment ID 和随机权重。
    // =========================================================
    H006_AfterObtained,


    // =========================================================
    // H007
    // 来源遗物：Toolbox
    //
    // Hook：
    // 第一回合起始手牌抽取之前
    //
    // 原版条件：
    // BeforeHandDraw
    // + player == Owner
    // + TurnNumber == 1
    // =========================================================
    H007_FirstTurnBeforeHandDraw
}