    // =========================================================
    // H031
    // 来源遗物：Planisphere
    //
    // 原版 Hook：
    // AfterRoomEntered(AbstractRoom room)
    //
    // 条件：
    // Owner.Creature.IsDead == false
    // && CurrentMapPoint != null
    // && CurrentMapPoint.PointType == Unknown
    // && CurrentRoomCount <= 1
